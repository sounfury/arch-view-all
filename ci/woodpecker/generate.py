#!/usr/bin/env python3
"""Generate the same eight Woodpecker quality gates for Clojure or Kotlin."""
import argparse
import json
import shlex
import sys
from pathlib import Path

IMAGE = "local/clojure-quality:1.0.0"
HEADER = "# Generated by ci/woodpecker/generate.py; edit quality/woodpecker.json.\n"
DEFAULT_LIMITS = {
    "cognitive": 15, "cyclomatic": 12, "nesting": 4,
    "params": 5, "file-length": 600, "duplication": 0,
}
GATES = (
    ("认知复杂度", "cognitive", "COMPLEXITY"),
    ("圈复杂度", "cyclomatic", "CYCLOMATIC"),
    ("嵌套深度", "nesting", "NESTING"),
    ("参数个数", "params", "PARAMS"),
    ("文件行数", "file-length", "FILE_LENGTH"),
    ("死代码", "dead-code", "DEAD_CODE"),
    ("重复代码", "duplication", "DUPLICATION"),
)


def yaml_text(value, indent=0):
    """Render JSON-compatible data as YAML without third-party dependencies."""
    prefix = " " * indent
    lines = []
    items = value.items() if isinstance(value, dict) else enumerate(value)
    for key, item in items:
        label = str(key) + ":" if isinstance(value, dict) else "-"
        if isinstance(item, (dict, list)):
            lines.append(prefix + label)
            lines.extend(yaml_text(item, indent + 2))
        else:
            lines.append(prefix + label + " " + json.dumps(item, ensure_ascii=False))
    return lines


def workflow(data):
    return HEADER + "\n".join(yaml_text(data)) + "\n"


def detekt_config(metric, limit):
    result: dict[str, object] = {"config": {"validation": True},
              "processors": {"active": False},
              "console-reports": {"active": True}}
    categories = ("comments", "complexity", "coroutines", "empty-blocks",
                  "exceptions", "naming", "performance", "potential-bugs", "style")
    for category in categories:
        result[category] = {"active": False}
    if metric == "dead-code":
        result["style"] = {"active": True, **{
            name: {"active": True} for name in (
                "UnusedImport", "UnusedParameter", "UnusedPrivateClass",
                "UnusedPrivateFunction", "UnusedPrivateProperty", "UnusedVariable")}}
    else:
        rule, option = {
            "cognitive": ("CognitiveComplexMethod", "allowedComplexity"),
            "cyclomatic": ("CyclomaticComplexMethod", "allowedComplexity"),
            "nesting": ("NestedBlockDepth", "allowedDepth"),
            "params": ("LongParameterList", "allowedFunctionParameters"),
            "file-length": ("LargeClass", "allowedLines"),
        }[metric]
        config = {"active": True, option: limit}
        if metric == "params":
            config.update(allowedConstructorParameters=6, ignoreDefaultParameters=False,
                          ignoreDataClasses=True)
        if metric == "cyclomatic":
            config.update(ignoreSimpleWhenEntries=True, ignoreNestingFunctions=True)
        result["complexity"] = {"active": True, rule: config}
    return workflow(result)


def gitleaks_config(policy):
    text = ('# Full default rules; only explicitly reviewed, exact exceptions below.\n'
            'title = "Full default secret scan"\n[extend]\nuseDefault = true\n')
    for entry in policy.get("secret_allowlists", []):
        # Escape literals for RE2; policy values cannot introduce broader regexes.
        def exact(value):
            return "^" + "".join("\\" + char if char in r"\.^$*+?{}[]|()" else char
                                 for char in value) + "$"

        text += "\n[[allowlists]]\n"
        for key, value in (
            ("description", entry["description"]),
            ("condition", "AND"), ("regexTarget", "secret"),
            ("targetRules", [entry["rule"]]),
            ("paths", [exact(entry["path"])]),
            ("regexes", [exact(entry["value"])]),
        ):
            text += key + " = " + json.dumps(value, ensure_ascii=False) + "\n"
    return text


def generate(policy):
    profile = policy["profile"]
    limits = policy["limits"]
    sources = shlex.join(policy["sources"])
    when = [{"event": ["push", "pull_request", "manual"]}]
    files = {}
    for title, metric, variable in GATES:
        if metric == "duplication":
            image = "node:22-bookworm-slim"
            commands = ["npm install --global jscpd@5.4.1",
                        "jscpd " + shlex.join(policy["duplication_sources"]) +
                        " --config quality/jscpd.json --no-colors --no-tips"]
        elif profile == "kotlin":
            image = "local/detekt-cli:2.0.0-alpha.6"
            config = f"quality/detekt-{metric}.yml"
            files[config] = detekt_config(metric, limits.get(metric))
            commands = ["java -jar /opt/detekt-cli.jar --input " +
                        shlex.quote(":".join(policy["sources"])) +
                        " --analysis-mode full --classpath " +
                        shlex.quote(":".join(policy.get("kotlin_classpath", ["/opt/detekt-cli.jar"]))) +
                        " --config " + config + " --fail-on-severity Info" +
                        " --excludes '**/build/**,**/.gradle/**' --base-path ."]
        else:
            image = IMAGE
            if metric == "cyclomatic":
                commands = ["crap complexity . --lang clojure --src " +
                            shlex.quote(policy["sources"][0]) +
                            f" --fail-on-complexity {limits[metric] + 1} --top 50"]
            elif metric == "dead-code":
                commands = ["dead-code " + sources]
            else:
                commands = [f'clojure-quality {metric} {limits[metric]} "$PWD" ' + sources]
        steps = []
        for nonblock in (False, True):
            step = {
                "name": title + ("（不阻断）" if nonblock else ""),
                "image": image,
                "when": [{"evaluate": f'SKIP_{variable} != "true" && '
                          f'{variable}_NONBLOCK {"==" if nonblock else "!="} "true"'}],
                "commands": commands,
            }
            if image.startswith("local/"):
                step["pull"] = False
            if nonblock:
                step["failure"] = "ignore"
            steps.append(step)
        files[f".woodpecker/{title}.yaml"] = workflow({"when": when, "steps": steps})
    files[".woodpecker/密钥扫描.yaml"] = workflow({
        "when": when,
        "clone": {"git": {"image": "woodpeckerci/plugin-git:2.10.1",
                           "settings": {"partial": False}}},
        "steps": [{"name": "密钥扫描", "image": "ghcr.io/gitleaks/gitleaks:v8.30.1",
                   "commands": [f"gitleaks {mode} . --config quality/gitleaks.toml "
                                "--redact=100 --verbose --no-banner --exit-code 1"
                                for mode in ("git", "dir")]}],
    })
    files["quality/gitleaks.toml"] = gitleaks_config(policy)
    files["quality/jscpd.json"] = json.dumps({
        "minLines": 5, "minTokens": 50, "threshold": limits["duplication"],
        "mode": "mild", "noGitignore": True, "maxSize": "1gb",
        "reporters": ["console", "threshold"], "absolute": False, "failOnEmpty": True,
        "ignore": ["**/.git/**", "**/node_modules/**", "**/build/**",
                   "**/.gradle/**", "**/target/**", "**/__pycache__/**"],
    }, ensure_ascii=False, indent=2) + "\n"
    return files


def validate(policy):
    if policy.get("version") != 1 or policy.get("profile") not in ("clojure", "kotlin"):
        raise ValueError("Expected version=1 and profile=clojure or kotlin")
    required = {"version", "profile", "sources", "duplication_sources", "limits"}
    allowed = required | {"secret_allowlists"}
    if policy["profile"] == "kotlin":
        allowed.add("kotlin_classpath")
    if not required.issubset(policy) or not set(policy).issubset(allowed):
        raise ValueError("Unknown or missing policy fields")
    exceptions = policy.get("secret_allowlists", [])
    if not isinstance(exceptions, list):
        raise ValueError("secret_allowlists must be a list")
    for entry in exceptions:
        if not isinstance(entry, dict) or set(entry) != {"description", "rule", "path", "value"}:
            raise ValueError("Each secret exception needs description, rule, path and exact value")
        if any(not isinstance(value, str) or not value.strip() or
               any(char in value for char in ("\n", "\r", "\0"))
               for value in entry.values()):
            raise ValueError("Secret exceptions must contain non-empty, single-line literals")
        path = Path(entry["path"])
        if path.is_absolute() or ".." in path.parts or entry["path"].startswith("-"):
            raise ValueError("Secret exception paths must be relative project files")
        if len(entry["value"]) < 8:
            raise ValueError("Secret exceptions must specify a complete match, not a short keyword")
    if "kotlin_classpath" in policy:
        classpath = policy["kotlin_classpath"]
        if not isinstance(classpath, list) or not classpath or any(
                not isinstance(path, str) or not path or path.startswith("-")
                for path in classpath):
            raise ValueError("kotlin_classpath must contain valid classpath entries")
    for key in ("sources", "duplication_sources"):
        if not isinstance(policy[key], list) or not policy[key]:
            raise ValueError(f"{key} must be a non-empty list")
        for source in policy[key]:
            if not isinstance(source, str) or not source or Path(source).is_absolute():
                raise ValueError("Sources must be non-empty relative paths")
            if ".." in Path(source).parts or source.startswith("-"):
                raise ValueError("Sources must remain inside the project")
    if policy["profile"] == "clojure" and len(policy["sources"]) != 1:
        raise ValueError("The crap Clojure backend requires one source root")
    if set(policy["limits"]) != set(DEFAULT_LIMITS):
        raise ValueError("All six thresholds must be specified")
    for key, value in policy["limits"].items():
        if type(value) is not int or value < (0 if key == "duplication" else 1):
            raise ValueError(f"Invalid threshold: {key}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path.cwd())
    parser.add_argument("--profile", choices=("clojure", "kotlin"))
    parser.add_argument("--source", action="append")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--update", action="store_true", help="Overwrite generated configuration")
    parser.add_argument("--migrate-tests", action="store_true",
                        help="Move root .woodpecker.yaml to .woodpecker/回归测试.yaml")
    args = parser.parse_args(argv)
    root = args.project.resolve(strict=True)
    policy_file = root / "quality/woodpecker.json"
    if policy_file.exists():
        policy = json.loads(policy_file.read_text())
        if args.profile or args.source:
            parser.error("Edit the existing quality/woodpecker.json to change its profile/sources")
    else:
        sources = args.source or ["src"]
        policy = {"version": 1, "profile": args.profile or "clojure",
                  "sources": sources, "duplication_sources": sources,
                  "limits": DEFAULT_LIMITS.copy()}
        if policy["profile"] == "kotlin":
            policy["kotlin_classpath"] = ["/opt/detekt-cli.jar"]
    validate(policy)
    files = generate(policy)
    files["quality/woodpecker.json"] = json.dumps(policy, ensure_ascii=False, indent=2) + "\n"
    changes = {name: text for name, text in files.items()
               if not (root / name).is_file() or (root / name).read_text() != text}
    if args.check:
        for name in changes:
            print("Out of date:", name)
        return int(bool(changes))
    root_candidates = [root / name for name in (".woodpecker.yaml", ".woodpecker.yml")
                       if (root / name).exists()]
    if len(root_candidates) > 1:
        parser.error("Multiple root workflows exist; consolidate them before migration")
    root_workflow = root_candidates[0] if root_candidates else root / ".woodpecker.yaml"
    destination = root / ".woodpecker/回归测试.yaml"
    if root_workflow.exists() and not args.migrate_tests:
        parser.error("Root workflow exists; use --migrate-tests to preserve it in .woodpecker/")
    if args.migrate_tests and root_workflow.exists() and destination.exists():
        parser.error("Refusing to overwrite the existing regression workflow")
    if not args.update:
        collisions = [name for name in changes if (root / name).exists()]
        if collisions:
            parser.error("Refusing to overwrite files; review and use --update: " + ", ".join(collisions))
    if args.migrate_tests and root_workflow.exists():
        destination.parent.mkdir(parents=True, exist_ok=True)
        root_workflow.rename(destination)
    for name, text in changes.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        print("Wrote", target)
    print("Ready: eight independent quality workflows; regression workflows preserved.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError) as error:
        print("Configuration error:", error, file=sys.stderr)
        sys.exit(1)
